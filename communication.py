"""Editable email drafts. Drafts are stored with sent=0 and are NEVER sent automatically."""
from config import POLICY_VERSION

def _mask(s): return s if len(s) < 6 else s[:2] + "*" * (len(s) - 5) + s[-3:]

def build_draft(form: dict, ref: str, decision: dict, results: list, open_requests=None) -> dict:
    name = form.get("contact_person") or "Vendor team"
    company = form.get("legal_name") or "your company"
    status = decision["status"]
    to_addr = decision.get("to_addr") or form.get("email", "")   # E2 sends to the previously registered email
    footer = "\n\nRegards,\nVendor Onboarding Team\n\n[DRAFT - generated by Kyvo, policy " + POLICY_VERSION + ". Human approval required before sending.]"
    if status == "APPROVED":
        return {"draft_type": "approval_confirmation", "to_addr": to_addr,
                "subject": f"[{ref}] Vendor registration approved - {company}",
                "body": f"Dear {name},\n\nThank you for completing your vendor registration for {company} (reference {ref}). "
                        f"All submitted details and documents passed our checks and your registration is approved.\n\n"
                        f"Note: these checks cover completeness, format and consistency; they do not replace statutory verification." + footer}
    # The follow-up list is the OPEN follow-up ledger when available, else the blocking results' asks.
    if open_requests is not None:
        asks = [r["ask"] for r in open_requests]
    else:
        asks = [r["action"] for r in results if r["blocking"] and r["status"] != "PASS" and r["action"]]
    seen, lines = set(), []
    for ask in asks:
        if ask in seen:
            continue
        seen.add(ask)
        lines.append(f"{len(lines) + 1}. {ask}")
    if status == "REJECTED":
        return {"draft_type": "rejection_notice", "to_addr": to_addr,
                "subject": f"[{ref}] Update on your vendor registration - {company}",
                "body": f"Dear {name},\n\nAfter review, we are unable to proceed with the registration of {company} (reference {ref}).\n\n"
                        + "\n".join(lines or ["Reason: policy disqualification (details to be shared by the reviewer)."]) + footer}
    return {"draft_type": "follow_up_request", "to_addr": to_addr,
            "subject": f"[{ref}] Action needed to complete your vendor registration - {company}",
            "body": f"Dear {name},\n\nThank you for registering {company} as a vendor (reference {ref}). "
                    f"We could not approve the registration yet. Please help us with the following:\n\n"
                    + "\n".join(lines) + "\n\nOnce you reply with the corrected details/documents, we will re-run the checks promptly." + footer}


def build_reminder(form: dict, ref: str, which: int, day: int, open_requests: list) -> dict:
    """A reminder draft (never sent) for the open follow-up items. which is 1 (day 3) or 2 (day 7)."""
    name = form.get("contact_person") or "Vendor team"
    company = form.get("legal_name") or "your company"
    footer = "\n\nRegards,\nVendor Onboarding Team\n\n[DRAFT - generated by Kyvo, policy " + POLICY_VERSION + ". Human approval required before sending.]"
    lines = [f"{i + 1}. {r['ask']}" for i, r in enumerate(open_requests)]
    return {"draft_type": f"reminder_{which}", "to_addr": form.get("email", ""),
            "subject": f"[{ref}] Reminder {which}: documents still needed - {company}",
            "body": f"Dear {name},\n\nThis is reminder {which} (around day {day}) about your pending vendor registration for "
                    f"{company} (reference {ref}). These items are still open:\n\n" + "\n".join(lines)
                    + "\n\nPlease reply so we can continue processing your application." + footer}
