# ---- policy lock -----------------------------------------------------------------
def read_lock():
    if not os.path.exists(LOCK_PATH):
        return None
    return yaml.safe_load(_read_bytes(LOCK_PATH).decode("utf-8"))

def current_lock():
    return {"semver": POLICY_SEMVER, "sha256": POLICY_SHA256, "version": POLICY_VERSION}

def write_lock():
    with open(LOCK_PATH, "w", encoding="utf-8") as fh:
        fh.write("# Generated by `python cli.py policy --lock`. Do not edit by hand.\n")
        yaml.safe_dump(current_lock(), fh, sort_keys=True)
    return current_lock()

def lock_status():
    """Returns (ok, message). ok is False when the policy file changed without the semver/lock being updated."""
    lock = read_lock()
    if lock is None:
        return False, "policy/kyvo_policy.lock is missing; run `python cli.py policy --lock`."
    if lock.get("sha256") != POLICY_SHA256:
        same_semver = lock.get("semver") == POLICY_SEMVER
        hint = " and bump `semver`" if same_semver else ""
        return False, f"policy file changed since the lock{hint}; run `python cli.py policy --lock`."
    return True, "policy lock matches the policy file."

