def _read_bytes(path):
    with open(path, "rb") as fh:
        return fh.read()

def load_policy(path=POLICY_PATH):
    raw = _read_bytes(path)
    data = yaml.safe_load(raw.decode("utf-8"))
    sha = hashlib.sha256(raw).hexdigest()
    return data, sha

POLICY, POLICY_SHA256 = load_policy()
POLICY_SEMVER = str(POLICY["semver"])
# Version = KYVO-POLICY-<semver>+<first 12 hex of the policy file's SHA-256>. Stored on every decision.
POLICY_VERSION = f"KYVO-POLICY-{POLICY_SEMVER}+{POLICY_SHA256[:12]}"

